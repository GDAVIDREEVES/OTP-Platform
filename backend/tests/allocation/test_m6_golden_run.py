    assert rerun["input_snapshot_hash"] == first["input_snapshot_hash"]
    h1 = store.get_artifact(first["run_id"], "output.sha256")["content"]
    h2 = store.get_artifact(rerun["run_id"], "output.sha256")["content"]
    assert h1 == h2
    rows1 = {_engine_id(r["charge_id"]): {k: v for k, v in r.items()
                                          if k not in ("charge_id", "run_id",
                                                       "documentation_ref")}
             for r in store.list_charges(run_id=first["run_id"])}
    rows2 = {_engine_id(r["charge_id"]): {k: v for k, v in r.items()
                                          if k not in ("charge_id", "run_id",
                                                       "documentation_ref")}
             for r in store.list_charges(run_id=rerun["run_id"])}
    assert rows1 == rows2


