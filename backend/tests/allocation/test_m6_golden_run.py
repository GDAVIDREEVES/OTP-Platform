def test_trueup_deltas_to_the_cent_with_booked_parents(golden):
    """SPEC §5.4 / §9.2 — one True-up row per (pool, provider, recipient,
    year), amounts to the cent, FX at the year-end closing rate, parent =
    the latest booked Budget charge."""
    res = golden["trueup"]
