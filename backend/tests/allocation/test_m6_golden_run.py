def _stage3_pools(period: str, source: str) -> tuple[list[dict], dict]:
    cfg = {**CONFIG, "period": period}
    ref = {k: FIXTURE[k] for k in ("entities", "cc_mapping", "pools",
                                   "markup_policies", "exclusions",
                                   "key_defs", "participation")}
    ref["key_values"] = FIXTURE["key_values"][source]
    lines = [r for r in FIXTURE["cost_lines"][source]
             if r["fiscal_period"] == period]
    s1 = stage1_capture_and_classify({"cost_lines": lines}, ref, cfg)
    s2 = stage2_pool({"classified_lines": s1["outputs"]["classified_lines"]},
                     ref, cfg)
    s3 = stage3_benefit_gate({"pools": s2["outputs"]["pools"]}, ref, cfg)
    return s3["outputs"]["pools"], {**ref}


def test_reciprocal_solution_matches_the_hand_solved_linear_system():
    """SPEC §9.2 — the engine's solved S equals the hand-solved 2×2 system
    (within the solver's 1e-10 tolerance) and conservation holds: the SCC
    charges out exactly its combined cost."""
    pools, ref = _stage3_pools("2026-01", "actual")
    res = cascade_allocate({"pools": pools}, ref, {**CONFIG, "period": "2026-01"})
    assert res["exceptions"] == []
    by_id = {p["pool_id"]: p for p in res["outputs"]["pools"]}
    # hand-solved literals (golden/build_fixture.py — independent derivation)
    assert abs(by_id[POOL_IT]["solved_cost"]
               - Decimal("470779.8561151079136690647482")) <= TOL
    assert abs(by_id[POOL_FIN]["solved_cost"]
               - Decimal("159731.6546762589928057553957")) <= TOL
    assert by_id[POOL_IT]["reciprocal_scc"] == [POOL_FIN, POOL_IT]
    # expected.json carries the solved system for every month
    for pool in (POOL_IT, POOL_FIN):
        assert abs(by_id[pool]["solved_cost"]
                   - Decimal(EXPECTED["solved"]["2026-01"][pool])) <= TOL
    # conservation (SPEC §9.3): total in == total charged out across the SCC
    scc_out = sum((a["allocated_cost"] for a in res["outputs"]["allocations"]
                   if a["pool_id"] in (POOL_IT, POOL_FIN)), ZERO)
    assert scc_out == (by_id[POOL_IT]["chargeable_base"]
                       + by_id[POOL_FIN]["chargeable_base"])


