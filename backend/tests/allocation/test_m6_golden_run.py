    assert rows["CHG-2026-POOL-MGMT-LE-DE-TRUEUP"]["fx_rate"] == "0.95"
    assert rows["CHG-2026-POOL-MGMT-LE-DE-TRUEUP"]["fx_rate_type"] == "Spot"
    assert rows["CHG-2026-POOL-FIN-SSC-LE-JP-TRUEUP"][
        "gross_charge_amount"] == "1444177"              # JPY @ 155, no decimals
    # FIN's markup base (own cost) never diverged — pure cost delta
    assert rows["CHG-2026-POOL-FIN-SSC-LE-DE-TRUEUP"]["markup_amount"] == "0.00"


